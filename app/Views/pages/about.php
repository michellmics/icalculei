    <h1>Sobre o Vibe2000</h1>
    <p class="lead">O portal das contas do dia a dia: calculadoras gratuitas, explicadas passo a passo, e notícias para entender o que muda no seu bolso.</p>

    <h2>O que fazemos</h2>
    <p>O Vibe2000 reúne calculadoras e conversores para as dúvidas mais comuns: quanto vou receber de férias, quanto rende um investimento, quantos dias úteis faltam para um prazo, qual combustível compensa. Cada ferramenta mostra o resultado na hora e explica a conta, com a fórmula e exemplos, para você entender de onde veio o número.</p>

    <h2>Como as calculadoras são revisadas</h2>
    <p>As regras e tabelas usadas nas calculadoras vêm de fontes oficiais, como a Receita Federal, o INSS, o Ministério da Previdência e a legislação publicada. Cada calculadora mostra a <b>data da última revisão</b> logo abaixo do título.</p>
    <p>Quando uma lei ou tabela muda, por exemplo o INSS e o Imposto de Renda no início de cada ano, as ferramentas afetadas são atualizadas e ganham uma nova data de revisão. Mesmo assim, os resultados são estimativas e podem ter diferenças em relação ao seu caso. Veja os <a href="/termos-de-uso">Termos de uso</a>.</p>

    <h2>Notícias e artigos</h2>
    <p>A seção de notícias explica, em linguagem simples, temas como direitos trabalhistas, impostos, juros e saúde, sempre com as calculadoras relacionadas ao lado para você fazer as suas contas. Os textos indicam a data de publicação e são atualizados quando as regras mudam.</p>

    <h2>Por que é gratuito</h2>
    <p>O Vibe2000 é mantido pela exibição de anúncios. Você não paga nada e não precisa se cadastrar. Os valores que você digita nas calculadoras ficam no seu navegador e não são enviados para nós. Saiba mais na <a href="/privacidade">Política de privacidade</a>.</p>

